def verify(out_dir):
    """Run Qayd over the written files and assert the planted facts."""
    sys.path.insert(0, ROOT)
    import io
    import json
    from qayd import cli

    def check(as_of):
        out, err = io.StringIO(), io.StringIO()
        code = cli.main(["check", "--dir", out_dir, "--as-of", as_of, "--json"], out, err)
        assert err.getvalue() == "", err.getvalue()
        return code, json.loads(out.getvalue())

    code, doc = check("2026-09-30")
    verdicts = dict((p["id"], p["verdict"]) for p in doc["policies"])
    assert all(v == "hold" for v in verdicts.values()), verdicts
    assert [f["code"] for f in doc["findings"]] == ["DECISION-DUE"], doc["findings"]
    assert code == 1
    code, doc = check("2026-09-14")
    assert code == 0 and doc["green"] is True, doc["findings"]
    code, doc = check("2026-07-31")
    verdicts = dict((p["id"], p["verdict"]) for p in doc["policies"])
    assert verdicts["WLT-01"] == "breach" and all(v == "hold" for k, v in verdicts.items() if k != "WLT-01"), verdicts
    code, doc = check("2026-03-31")
    verdicts = dict((p["id"], p["verdict"]) for p in doc["policies"])
    assert verdicts["WLT-03"] == "missing" and all(v == "hold" for k, v in verdicts.items() if k != "WLT-03"), verdicts
    code, doc = check("2025-11-30")
    verdicts = dict((p["id"], p["verdict"]) for p in doc["policies"])
    assert verdicts["WLT-05"] == "kill" and all(v == "hold" for k, v in verdicts.items() if k != "WLT-05"), verdicts
    code, doc = check("2025-12-31")
    kill = [p for p in doc["policies"] if p["id"] == "WLT-05"][0]
    assert kill["verdict"] == "hold" and "closed by D-2025-12-05" in kill["reason"], kill
    for as_of in ("2025-01-31", "2025-06-30", "2025-10-31", "2026-01-31", "2026-05-31", "2026-08-31"):
        code, doc = check(as_of)
        assert code == 0 and doc["green"] is True, (as_of, doc["findings"])


def main(argv):
    out_dir = os.path.join(ROOT, "examples")
    args = list(argv)
    if args[:1] == ["--out"] and len(args) == 2:
        out_dir = args[1]
    elif args:
        sys.stderr.write("usage: python3 tools/make_example.py [--out DIR]\n")
        return 2
    os.makedirs(out_dir, exist_ok=True)
    files = build()
    for name, text in files.items():
        with open(os.path.join(out_dir, name), "wb") as fh:
            fh.write(text.encode("utf-8"))
    verify(out_dir)
    sys.stdout.write("wrote %d files to %s and verified the planted facts\n" % (len(files), out_dir))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
