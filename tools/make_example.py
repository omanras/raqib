    fun = ["cafe", "books", "cinema", "gift", "takeaway"]
    savings = 4000000          # baisa
    transfers = 0
    for index, (y, m) in enumerate(months()):
        ym = "%04d-%02d" % (y, m)
        d = lambda day: "%s-%02d" % (ym, day)
        rate = 3850 + rng.randint(-10, 10)                     # per 10000
        rates.append("%s,USD,0.%04d" % (d(1), rate))
        ledger.append("%s,1200.000,OMR,salary,salary,,salary %s" % (d(1), ym))
        if ym != "2026-03":                                      # the planted missing routine
            ledger.append("%s,-300.000,OMR,salary,transfer,transfer,to savings" % d(3))
            ledger.append("%s,300.000,OMR,savings,transfer,transfer,from salary" % d(3))
            savings += 300000
            transfers += 1
        ledger.append("%s,-300.000,OMR,salary,housing,,rent %s" % (d(5), ym))
        ledger.append("%s,-45.000,OMR,salary,transport,,fuel" % d(8))
        ledger.append("%s,-100.000,OMR,salary,family,,family support" % d(10))
        for day in (12, 18, 24):
            ledger.append("%s,%s,OMR,cash,food,,%s" % (d(day), omr(-rng.randint(25000, 55000)), rng.choice(foods)))
        ledger.append("%s,%s,OMR,cash,discretionary,,%s" % (d(15), omr(-rng.randint(10000, 40000)), rng.choice(fun)))
        if rng.random() < 0.5:
            ledger.append("%s,%s,OMR,cash,discretionary,,%s" % (d(27), omr(-rng.randint(10000, 40000)), rng.choice(fun)))
        if ym == "2026-07":                                      # the planted breach
            ledger.append("%s,-125.000,OMR,cash,discretionary,,new phone" % d(20))
        elif rng.random() < 0.25:
            ledger.append("%s,%s,OMR,salary,side,,freelance work" % (d(20), omr(rng.randint(50000, 150000))))
        if ym == "2024-10":                                      # the broker pilot starts
            ledger.append("%s,-500.000,OMR,salary,transfer,transfer,to broker" % d(10))
            ledger.append("%s,500.000,OMR,broker,transfer,transfer,from salary" % d(10))
