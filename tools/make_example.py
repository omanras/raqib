def months():
    y, m = FIRST
    out = []
    while (y, m) <= LAST:
        out.append((y, m))
        m += 1
        if m == 13:
            y, m = y + 1, 1
    return out


def last_day(y, m):
    if m == 12:
        return datetime.date(y, 12, 31)
    return datetime.date(y, m + 1, 1) - datetime.timedelta(days=1)


def omr(baisa):
    """Integer baisa (thousandths) -> OMR text with three decimals."""
    sign = "-" if baisa < 0 else ""
    baisa = abs(baisa)
    return "%s%d.%03d" % (sign, baisa // 1000, baisa % 1000)


def usd(cents):
    sign = "-" if cents < 0 else ""
    cents = abs(cents)
    return "%s%d.%02d" % (sign, cents // 100, cents % 100)


